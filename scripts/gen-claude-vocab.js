// Reads the Claude BPE vocabulary from @anthropic-ai/tokenizer (which ships
// claude.json) and writes it as a plain ES module so it can be imported
// without JSON import assertions in Node v22+ or any Vite version.
//
// Runs automatically after: pnpm install  (via "postinstall" in package.json)
// Also run manually:  node scripts/gen-claude-vocab.js

import { createRequire } from 'module';
import { writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const __dir  = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dir, '..', 'core', 'claude-vocab.js');

try {
  const req  = createRequire(import.meta.url);
  const data = req('@anthropic-ai/tokenizer/claude.json');

  const content = [
    '// Auto-generated by scripts/gen-claude-vocab.js — do not edit manually.',
    '// Re-run:  node scripts/gen-claude-vocab.js',
    `export default ${JSON.stringify(data)};`,
    '',
  ].join('\n');

  writeFileSync(outPath, content, 'utf8');
  console.log('✓ core/claude-vocab.js generated');
} catch (err) {
  console.error('✗ Failed to generate claude-vocab.js:', err.message);
  process.exit(1);
}
